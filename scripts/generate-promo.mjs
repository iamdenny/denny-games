// Original Denny Games artwork; no third-party assets. Rebuild with Playwright Chromium.
import { chromium } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
const sizes = [
  [728, 90],
  [970, 250],
  [300, 250],
  [336, 280],
  [160, 600],
  [300, 600],
  [320, 50],
  [320, 100],
  [1080, 1080],
  [1080, 1920],
];
const browser = await chromium.launch();
await mkdir("public/promo", { recursive: true });
for (const locale of ["en", "ko"])
  for (const [w, h] of sizes) {
    const tiny = h <= 100,
      tall = h > w,
      social = w === 1080;
    const scale = social ? 3 : 1;
    const width = w / scale,
      height = h / scale;
    const compact = h === 50;
    const headline =
      locale === "ko"
        ? "잠깐의 휴식,\n한 판의 즐거움."
        : "Small games.\nBig little breaks.";
    const cta = locale === "ko" ? "지금 플레이 →" : "Play now →";
    const tiles = `<div class="tiles">${["2", "4", "8", "16"].map((n, i) => `<span style="background:${["#a7f0e6", "#ef896b", "#d9ed68", "#f5f2e9"][i]};transform:rotate(${i % 2 ? 8 : -7}deg)">${n}</span>`).join("")}</div>`;
    const html = `<!doctype html><html lang="${locale}"><meta charset="utf-8"><style>
  *{box-sizing:border-box}body{margin:0;width:${width}px;height:${height}px;background:#17211d;color:#f5f2e9;font-family:Arial,'Apple SD Gothic Neo',sans-serif;overflow:hidden;border:1px solid #606b61;padding:${compact ? 6 : tiny ? 14 : 22}px;display:flex;${tiny ? "align-items:center;gap:20px" : "flex-direction:column;justify-content:space-between"};position:relative}
  .brand{font-size:${compact ? 13 : tiny ? 18 : 21}px;font-weight:900;letter-spacing:-.8px;white-space:nowrap}.brand b{color:#d9ed68}h1{font-size:${tall && w === 160 ? 25 : 36}px;letter-spacing:-1.6px;line-height:1.12;white-space:pre-line;margin:18px 0}p{font-size:14px;color:#a7f0e6;line-height:1.5;margin:12px 0}.cta{background:#d9ed68;color:#17211d;border-radius:30px;padding:${compact ? "8px 10px" : "12px 18px"};font-size:${compact ? 11 : 14}px;font-weight:800;display:inline-block;white-space:nowrap}.url{font-size:11px;letter-spacing:.4px;color:#f5f2e9;margin-top:14px}.tiles{display:grid;grid-template-columns:repeat(2,1fr);gap:10px;width:${tall ? 120 : 100}px;align-self:center;margin:18px 0}.tiles span{display:grid;place-items:center;aspect-ratio:1;border-radius:12px;color:#17211d;font-size:27px;font-weight:900;box-shadow:0 5px 0 #0004}.body{${!tiny && !tall && w > 400 ? "display:flex;justify-content:space-between;align-items:center;" : ""}}.tag{font-size:${compact ? 10 : 12}px;color:#a7f0e6;margin-top:5px}.end{${tiny ? "margin-left:auto;" : ""}}
  ${!tiny && !tall && width < 400 ? "h1{font-size:27px;margin:10px 0}p{font-size:12px;margin:8px 0}.tiles{position:absolute;right:22px;bottom:22px;width:70px;gap:6px;margin:0}.tiles span{font-size:19px;border-radius:8px}.url{font-size:10px;margin-top:8px}.body{display:block}.cta{padding:10px 14px}" : ""}
  ${w === 160 ? ".brand{font-size:15px}.url{font-size:9px;letter-spacing:0}.cta{font-size:12px;padding:12px 9px}.tiles{width:100px}" : ""}
  ${!tiny && !tall && width >= 400 ? "h1{font-size:30px;margin:0;line-height:1.1}p{font-size:12px;margin:4px 0}.tiles{margin:0}.url{margin-top:8px}.cta{padding:10px 18px}" : ""}
  </style><div class="brand">DENNY <b>GAMES.</b>${tiny ? `<div class="tag">${locale === "ko" ? "설치 없이 무료 웹게임" : "Free browser games"}</div>` : ""}</div>${tiny ? (w > 400 ? `<div style="font-size:${w > 800 ? 25 : 19}px;font-weight:700">${locale === "ko" ? "잠깐의 휴식, 한 판의 즐거움." : "Small games. Big little breaks."}</div>` : "") : `<div class="body"><div><h1>${headline}</h1><p>${locale === "ko" ? "설치 없이, 브라우저에서.<br>무료 게임을 만나보세요." : "Your next break starts here.<br>Free games. No download."}</p></div>${tiles}</div>`}<div class="end"><span class="cta">${cta}</span>${!tiny ? '<div class="url">games.iamdenny.com</div>' : ""}</div></html>`;
    const page = await browser.newPage({
      viewport: { width: w, height: h },
      deviceScaleFactor: 1,
    });
    await page.setContent(html);
    if (scale > 1)
      await page.addStyleTag({
        content: `body{transform:scale(${scale});transform-origin:top left}`,
      });
    await page.screenshot({
      path: `public/promo/denny-games-${locale}-${w}x${h}.png`,
    });
    await page.close();
  }
await browser.close();
await writeFile(
  "public/promo/README.txt",
  "Original Denny Games promotional artwork. Use to link to https://games.iamdenny.com/. Do not imply endorsement or alter branding. Generated by scripts/generate-promo.mjs.\n",
);
